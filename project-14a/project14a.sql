INSERT INTO DW_STRUCTURED_EVENTS(
EVENT_ID,
EVENT_TIME,
USER_ID,
PAGE,
ACTION,
ORDER_TOTAL,
SHIPPING_COST,
TAX,
ITEMS,
PROMO_CODE,
DISCOUNT_AMOUNT,
NET_REVENUE
)
