-- EXTRACT JSON FIELDS 
SELECT RAW_EVENT:event_id::STRING AS EVENT_ID,
RAW_EVENT:timestamp::TIMESTAMP AS EVENT_TIME,
RAW_EVENT:user_id:NUMBER AS USER_ID,
RAW_EVENT:action::STRING AS ACTION,
RAW_EVENT:order:total::NUMBER(12,2) AS ORDER_TOTAL,
RAW_EVENT:promo_code::STRING AS PROMO_CODE FROM LAKE_RAW_EVENTS 
ORDER BY EVENT_TIME;

--CALCULATE NET REVENUE 
SELECT RAW_EVENT:event_id::STRING AS EVENT_ID,
RAW_EVENT:order:total::NUMBER(12,2) AS ORDER_TOTAL,
RAW_EVENT:order:shipping_cost::NUMBER(12,2) AS SHIPPPING_COST,
RAW_EVENT:order:tax::NUMBER(12,2) AS TAX,
COALESCE(
RAW_EVENT:discount_amount::NUMBER(12,2),0
) AS DISCOUNT_AMOUNT,
(
RAW_EVENT:order:total::NUMBER(12,2)
-RAW_EVENT:order:shipping_cost::NUMBER(12,2)
-RAW_EVENT:order:tax::NUMBER(12,2)
-COALESCE(
RAW_EVENT:discount_amount::NUMBER(12,2),0
)
) AS NET_REVENUE FROM LAKE_RAW_EVENTS 
WHERE RAW_EVENT:order:total::NUMBER(12,2)>0 ORDER BY EVENT_ID;

-- CALCULATE FUNNEL KPIs
SELECT
    COUNT(*) AS TOTAL_EVENTS,

    COUNT_IF(
        RAW_EVENT:action::STRING = 'purchase'
        AND RAW_EVENT:order:total::NUMBER(12,2) > 0
    ) AS TOTAL_PURCHASES,

    ROUND(
        COUNT_IF(
            RAW_EVENT:action::STRING = 'purchase'
            AND RAW_EVENT:order:total::NUMBER(12,2) > 0
        ) * 100.0 / COUNT(*),
        2
    ) AS CONVERSION_RATE_PCT,

    SUM(
        CASE
            WHEN RAW_EVENT:action::STRING = 'purchase'
                 AND RAW_EVENT:order:total::NUMBER(12,2) > 0
            THEN RAW_EVENT:order:total::NUMBER(12,2)
            ELSE 0
        END
    ) AS TOTAL_GROSS_REVENUE,

    ROUND(
        SUM(
            CASE
                WHEN RAW_EVENT:action::STRING = 'purchase'
                     AND RAW_EVENT:order:total::NUMBER(12,2) > 0
                THEN RAW_EVENT:order:total::NUMBER(12,2)
                ELSE 0
            END
        )
        /
        NULLIF(
            COUNT_IF(
                RAW_EVENT:action::STRING = 'purchase'
                AND RAW_EVENT:order:total::NUMBER(12,2) > 0
            ),
            0
        ),
        2
    ) AS AVERAGE_ORDER_VALUE

FROM LAKE_RAW_EVENTS;

