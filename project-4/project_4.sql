--FACT SALES 
CREATE OR REPLACE TABLE FACT_SALES(
SALE_ID NUMBER NOT NULL,CUSTOMER_KEY NUMBER NOT NULL,PRODUCT_KEY NUMBER NOT NULL,
BRANCH_KEY NUMBER NOT NULL,DATE_KEY NUMBER NOT NULL,QUANTITY NUMBER NOT NULL,
TOTAL_AMOUNT NUMBER(14,2) NOT NULL,
CONSTRAINT PK_FACT_SALES PRIMARY KEY (SALE_ID)
);
INSERT INTO FACT_SALES(
SALE_ID,CUSTOMER_KEY,PRODUCT_KEY,BRANCH_KEY,DATE_KEY,QUANTITY,TOTAL_AMOUNT 
) SELECT S.SALE_ID,C.CUSTOMER_KEY,P.PRODUCT_KEY,B.BRANCH_KEY,D.DATE_KEY,
S.QUANTITY,S.TOTAL_AMOUNT FROM STG_SALES S JOIN DIM_CUSTOMER C 
ON S.CUSTOMER_ID=C.CUSTOMER_ID JOIN DIM_PRODUCT P ON S.PRODUCT_ID=P.PRODUCT_ID
JOIN DIM_BRANCH B ON S.BRANCH_ID=B.BRANCH_ID JOIN DIM_DATE D ON S.DATE_ID=D.DATE_ID;
SELECT * FROM FACT_SALES ORDER BY SALE_ID LIMIT 20;

--CHECK FOR DUPLICATE SALE IDS
SELECT SALE_ID,COUNT(*) AS CNT FROM FACT_SALES GROUP BY SALE_ID HAVING COUNT(*)>1;

--VALIDATE ORPHAN RECORDS
SELECT COUNT(*) AS ORPHAN_CUSTOMERS FROM FACT_SALES F LEFT JOIN DIM_CUSTOMER C 
ON F.CUSTOMER_KEY=C.CUSTOMER_KEY WHERE C.CUSTOMER_KEY IS NULL;
--PRODUCT
SELECT COUNT(*) AS ORPHAN_PRODUCTS FROM FACT_SALES F LEFT JOIN DIM_PRODUCT P 
ON F.PRODUCT_KEY=P.PRODUCT_KEY WHERE P.PRODUCT_KEY IS NULL;
--BRANCH
SELECT COUNT(*) AS ORPHAN_BRANCHES FROM FACT_SALES F LEFT JOIN DIM_BRANCH B 
ON F.BRANCH_KEY=B.BRANCH_KEY WHERE B.BRANCH_KEY IS NULL;
--DATE
SELECT COUNT(*) AS ORPHAN_DATES FROM FACT_SALES F LEFT JOIN DIM_DATE D 
ON F.DATE_KEY=D.DATE_KEY WHERE D.DATE_KEY IS NULL;

--TOTAL REVENUE
SELECT SUM(QUANTITY) AS TOTAL_QUANTITY,SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE FROM FACT_SALES;

--CUSTOMER REVENUE REPORT
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,C.MEMBERSHIP,SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE 
FROM FACT_SALES F JOIN DIM_CUSTOMER C ON F.CUSTOMER_KEY=C.CUSTOMER_KEY 
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME,C.MEMBERSHIP ORDER BY TOTAL_REVENUE DESC;

--PRODUCT REVENUE REPORT
SELECT P.PRODUCT_ID,P.PRODUCT_NAME,P.CATEGORY,P.BRAND,SUM(F.QUANTITY) AS TOTAL_QUANTITY,
SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM FACT_SALES F JOIN DIM_PRODUCT P 
ON F.PRODUCT_KEY=P.PRODUCT_KEY GROUP BY P.PRODUCT_ID,P.PRODUCT_NAME,P.CATEGORY,
P.BRAND ORDER BY TOTAL_REVENUE DESC;

--BRANCH PERFORMANCE
SELECT B.BRANCH_ID,B.BRANCH_NAME,B.CITY,B.STATE,B.REGION,SUM(F.QUANTITY) AS TOTAL_QUANTITY,
SUM(F.TOTAL_AMOUNT) AS TOTAL_SALES FROM FACT_SALES F JOIN DIM_BRANCH B 
ON F.BRANCH_KEY=B.BRANCH_KEY GROUP BY B.BRANCH_ID,B.BRANCH_NAME,B.CITY,B.STATE,
B.REGION ORDER BY TOTAL_SALES DESC;

--MONTHLY REVENUE
SELECT D.YEAR,D.MONTH,SUM(F.TOTAL_AMOUNT) AS MONTHLY_REVENUE FROM FACT_SALES F 
JOIN DIM_DATE D ON F.DATE_KEY=D.DATE_KEY GROUP BY D.YEAR,D.MONTH ORDER BY D.YEAR,
MIN(D.DATE_VALUE);

--STATE WISE SALES
SELECT C.STATE,SUM(F.TOTAL_AMOUNT) AS TOTAL_SALES FROM FACT_SALES F 
JOIN DIM_CUSTOMER C ON F.CUSTOMER_KEY=C.CUSTOMER_KEY GROUP BY C.STATE 
ORDER BY TOTAL_SALES DESC;

--CATEGORY WISE REVENUE
SELECT P.CATEGORY,SUM(F.QUANTITY) AS TOTAL_QUANTITY,SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM FACT_SALES F 
JOIN DIM_PRODUCT P ON F.PRODUCT_KEY=P.PRODUCT_KEY GROUP BY P.CATEGORY
ORDER BY TOTAL_REVENUE DESC;

--TOP 10 CUSTOMERS
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,SUM(F.TOTAL_AMOUNT) AS TOTAL_SALES FROM FACT_SALES F 
JOIN DIM_CUSTOMER C ON F.CUSTOMER_KEY=C.CUSTOMER_KEY GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME
ORDER BY TOTAL_SALES DESC LIMIT 10;

--TOP 10 PRODUCTS
SELECT P.PRODUCT_ID,P.PRODUCT_NAME,P.CATEGORY,SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM FACT_SALES F 
JOIN DIM_PRODUCT P ON F.PRODUCT_KEY=P.PRODUCT_KEY GROUP BY P.PRODUCT_ID,P.PRODUCT_NAME,P.CATEGORY 
ORDER BY TOTAL_REVENUE DESC LIMIT 10;

--SALES TREND ANALYSIS
SELECT D.DATE_VALUE,SUM(F.TOTAL_AMOUNT) AS DAILY_SALES FROM FACT_SALES F 
JOIN DIM_DATE D ON F.DATE_KEY=D.DATE_KEY GROUP BY D.DATE_VALUE ORDER BY D.DATE_VALUE;

--QUARTERLY REVENUE 
SELECT D.YEAR,D.QUARTER,SUM(F.TOTAL_AMOUNT) AS QUARTERY_REVENUE FROM FACT_SALES F 
JOIN DIM_DATE D ON F.DATE_KEY=D.DATE_KEY GROUP BY D.YEAR,D.QUARTER 
ORDER BY D.YEAR,D.QUARTER;

--MEMBERSHIP-WISE REVENUE 
SELECT C.MEMBERSHIP,COUNT(DISTINCT C.CUSTOMER_ID) AS CUSTOMER_COUNT,
SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM FACT_SALES F 
JOIN DIM_CUSTOMER C ON F.CUSTOMER_KEY=C.CUSTOMER_KEY GROUP BY C.MEMBERSHIP 
ORDER BY TOTAL_REVENUE DESC;

--REGION WISE REVENUE
SELECT B.REGION,SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM FACT_SALES F 
JOIN DIM_BRANCH B ON F.BRANCH_KEY=B.BRANCH_KEY GROUP BY B.REGION 
ORDER BY TOTAL_REVENUE DESC; 

--WEEKEND VS WEEKDAY SALES
SELECT D.IS_WEEKEND,SUM(F.TOTAL_AMOUNT) AS TOTAL_SALES,SUM(F.QUANTITY) AS TOTAL_QUANTITY FROM FACT_SALES F 
JOIN DIM_DATE D ON F.DATE_KEY=D.DATE_KEY GROUP BY D.IS_WEEKEND 
ORDER BY TOTAL_SALES DESC;

--AVG TRANSACTION VALUE
SELECT AVG(TOTAL_AMOUNT) AS AVERAGE_TRANSACTION_VALUE FROM FACT_SALES;

--PRODUCT CATEGORY+BRANCH ANALYSIS
SELECT B.BRANCH_NAME,P.CATEGORY,SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM FACT_SALES F 
JOIN DIM_BRANCH B ON F.BRANCH_KEY=B.BRANCH_KEY JOIN DIM_PRODUCT P 
ON F.PRODUCT_KEY=P.PRODUCT_KEY GROUP BY B.BRANCH_NAME,P.CATEGORY 
ORDER BY B.BRANCH_NAME,TOTAL_REVENUE DESC;

--CHECK THE GRAIN 
SELECT F.SALE_ID,C.CUSTOMER_NAME,P.PRODUCT_NAME,B.BRANCH_NAME,D.DATE_VALUE,F.QUANTITY,
F.TOTAL_AMOUNT FROM FACT_SALES F JOIN DIM_CUSTOMER C ON F.CUSTOMER_KEY=C.CUSTOMER_KEY 
JOIN DIM_PRODUCT P ON F.PRODUCT_KEY=P.PRODUCT_KEY JOIN DIM_BRANCH B ON 
F.BRANCH_KEY=B.BRANCH_KEY JOIN DIM_DATE D ON F.DATE_KEY=D.DATE_KEY 
ORDER BY F.SALE_ID LIMIT 20;

