PRODUCT_KEY NUMBER AUTOINCREMENT,PRODUCT_ID NUMBER NOT NULL,
PRODUCT_NAME VARCHAR(100),
CATEGORY VARCHAR(100),BRAND VARCHAR(100),PRICE NUMBER(12,2),
