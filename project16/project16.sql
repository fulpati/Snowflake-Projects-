SELECT * FROM STRM_BRONZE_CLAIMS;

MERGE INTO SILVER_CLAIMS_TRANSACTIONS AS TARGET 
USING (
SELECT 
PAYLOAD:claim_id::VARCHAR AS CLAIM_ID,
PAYLOAD:submitted_at::TIMESTAMP_TZ AS SUBMITTED_AT,
PAYLOAD:patient_id::NUMBER AS PATIENT_ID,
PAYLOAD:provider_id::VARCHAR AS PROVIDER_ID,
PAYLOAD:diagnosis_code::VARCHAR AS DIAGNOSIS_CODE,
PAYLOAD:billed_amount::NUMBER(18,2) AS BILLED_AMOUNT,
PAYLOAD:copay_amount::NUMBER(18,2) AS COPAY_AMOUNT,
PAYLOAD:billed_amount::NUMBER(18,2) - PAYLOAD:copay_amount::NUMBER(18,2) AS NET_PAYABLE_AMOUNT,
PAYLOAD:status::VARCHAR AS STATUS FROM STRM_BRONZE_CLAIMS 
QUALIFY ROW_NUMBER() OVER (
PARTITION BY PAYLOAD:claim_id::VARCHAR 
ORDER BY METADATA$ROW_ID DESC 
) = 1 
) AS SOURCE 
ON TARGET.CLAIM_ID = SOURCE.CLAIM_ID 
WHEN MATCHED THEN UPDATE SET 
TARGET.SUBMITTED_AT=SOURCE.SUBMITTED_AT,
TARGET.PATIENT_ID=SOURCE.PATIENT_ID,
TARGET.PROVIDER_ID=SOURCE.PROVIDER_ID,
TARGET.DIAGNOSIS_CODE=SOURCE.DIAGNOSIS_CODE,
TARGET.BILLED_AMOUNT=SOURCE.BILLED_AMOUNT,
TARGET.COPAY_AMOUNT=SOURCE.COPAY_AMOUNT,
TARGET.NET_PAYABLE_AMOUNT=SOURCE.NET_PAYABLE_AMOUNT,
TARGET.STATUS=SOURCE.STATUS
WHEN NOT MATCHED THEN INSERT(
CLAIM_ID,
SUBMITTED_AT,
PATIENT_ID,
PROVIDER_ID,
DIAGNOSIS_CODE,
BILLED_AMOUNT,
COPAY_AMOUNT,
NET_PAYABLE_AMOUNT,
STATUS
)
VALUES (
SOURCE.CLAIM_ID,
SOURCE.SUBMITTED_AT,
SOURCE.PATIENT_ID,
SOURCE.PROVIDER_ID,
SOURCE.DIAGNOSIS_CODE,
SOURCE.BILLED_AMOUNT,
SOURCE.COPAY_AMOUNT,
SOURCE.NET_PAYABLE_AMOUNT,
SOURCE.STATUS
);

SELECT * FROM SILVER_CLAIMS_TRANSACTIONS ORDER BY CLAIM_ID; 

CREATE OR REPLACE DYNAMIC TABLE DT_PROVIDER_FINANCIAL_SUMMARY 
TARGET_LAG='1 minute'
WAREHOUSE=COMPUTE_WH 
AS 
SELECT 
PROVIDER_ID,
SUM(BILLED_AMOUNT) AS TOTAL_BILLED_AMOUNT,
SUM(COPAY_AMOUNT) AS TOTAL_COPAY_COLLECT,
SUM(NET_PAYABLE_AMOUNT) AS TOTAL_NET_PAYABLE,
COUNT(*) AS APPROVED_CLAIMS FROM SILVER_CLAIMS_TRANSACTIONS 
WHERE STATUS='APPROVED' GROUP BY PROVIDER_ID;

SELECT * FROM DT_PROVIDER_FINANCIAL_SUMMARY ORDER BY PROVIDER_ID;

SELECT
    NAME AS DYNAMIC_TABLE_NAME,
    REFRESH_ACTION,
    STATE,
    REFRESH_TRIGGER,
    REFRESH_START_TIME,
    REFRESH_END_TIME
FROM TABLE(
    INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY(
        NAME => 'HEALTHCARE_PIPELINE_DB.CLAIMS_CORE.DT_PROVIDER_FINANCIAL_SUMMARY'
    )
)
ORDER BY REFRESH_START_TIME DESC;

SELECT
    NAME AS DYNAMIC_TABLE_NAME,
    DATABASE_NAME,
    SCHEMA_NAME,
    QUALIFIED_NAME,
    INPUTS,
    TARGET_LAG_TYPE,
    TARGET_LAG_SEC,
    SCHEDULING_STATE,
    ALTER_TRIGGER
FROM TABLE(
    INFORMATION_SCHEMA.DYNAMIC_TABLE_GRAPH_HISTORY()
)
WHERE NAME = 'DT_PROVIDER_FINANCIAL_SUMMARY';

