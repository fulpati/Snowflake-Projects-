CREATE OR REPLACE TABLE SILVER_CLAIMS_TRANSACTIONS(
CLAIM_ID VARCHAR,
SUBMITTED_AT TIMESTAMP_TZ,
PATIENT_ID NUMBER,
PROVIDER_ID VARCHAR,
DIAGNOSIS_CODE VARCHAR,
BILLED_AMOUNT NUMBER(18,2),
COPAY_AMOUNT NUMBER(18,2),
NET_PAYABLE_AMOUNT NUMBER(18,2),
STATUS VARCHAR
);

INSERT INTO SILVER_CLAIMS_TRANSACTIONS(
CLAIM_ID,
SUBMITTED_AT,
PATIENT_ID,
PROVIDER_ID,
DIAGNOSIS_CODE,
BILLED_AMOUNT,
COPAY_AMOUNT,
NET_PAYABLE_AMOUNT,
STATUS
)
SELECT CLAIM_ID,SUBMITTED_AT,PATIENT_ID,PROVIDER_ID,DIAGNOSIS_CODE,BILLED_AMOUNT,
COPAY_AMOUNT,BILLED_AMOUNT - COPAY_AMOUNT AS NET_PAYABLE_AMOUNT, STATUS 
FROM (
SELECT PAYLOAD:claim_id::VARCHAR AS CLAIM_ID,
PAYLOAD:submitted_at::TIMESTAMP_TZ AS SUBMITTED_AT,
PAYLOAD:patient_id::NUMBER AS PATIENT_ID,
PAYLOAD:provider_id::VARCHAR AS PROVIDER_ID,
PAYLOAD:diagnosis_code::VARCHAR AS DIAGNOSIS_CODE,
PAYLOAD:billed_amount::NUMBER(18,2) AS BILLED_AMOUNT,
PAYLOAD:copay_amount::NUMBER(18,2) AS COPAY_AMOUNT,
PAYLOAD:status::VARCHAR AS STATUS,
ROW_NUMBER() OVER (
PARTITION BY PAYLOAD:claim_id::VARCHAR 
ORDER BY INGEST_ID DESC 
) AS RN FROM BRONZE_RAW_CLAIMS 
)
WHERE RN=1;

SELECT * FROM SILVER_CLAIMS_TRANSACTIONS ORDER BY CLAIM_ID;

