CREATE OR REPLACE TABLE DIM_MONTH (
    MONTH_KEY INTEGER AUTOINCREMENT,
    MONTH_NAME VARCHAR(20) NOT NULL,
    QUARTER_KEY INTEGER NOT NULL,

    CONSTRAINT PK_DIM_MONTH
        PRIMARY KEY (MONTH_KEY),

    CONSTRAINT FK_MONTH_QUARTER
        FOREIGN KEY (QUARTER_KEY)
        REFERENCES DIM_QUARTER(QUARTER_KEY)
);
INSERT INTO DIM_MONTH (
    MONTH_NAME,
    QUARTER_KEY
)
