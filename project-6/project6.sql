SELECT
    COUNT(*) AS TOTAL_TRANSACTIONS,
    COUNT(DISTINCT SALE_ID) AS UNIQUE_SALES,
    SUM(QUANTITY) AS TOTAL_UNITS_SOLD,
    SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES;