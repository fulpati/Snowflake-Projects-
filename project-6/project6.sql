--CREATE DIMENIONS TABLES AND LOAD THE DATA INTO THEM
CREATE OR REPLACE TABLE DIM_REGION(
REGION_KEY INTEGER AUTOINCREMENT,
REGION_NAME VARCHAR(50) NOT NULL,
CONSTRAINT PK_DIM_REGION PRIMARY KEY (REGION_KEY)
);
INSERT INTO DIM_REGION (REGION_NAME) 
SELECT DISTINCT REGION FROM STG_BRANCHES ORDER BY REGION;

CREATE OR REPLACE TABLE DIM_STATE(
STATE_KEY INTEGER AUTOINCREMENT,
STATE_NAME VARCHAR(100) NOT NULL,
REGION_KEY INTEGER,
CONSTRAINT PK_DIM_STATE PRIMARY KEY (STATE_KEY),
CONSTRAINT FK_STATE_REGION FOREIGN KEY (REGION_KEY) REFERENCES DIM_REGION(REGION_KEY)
);
INSERT INTO DIM_STATE (
    STATE_NAME,
    REGION_KEY
)
SELECT
    X.STATE_NAME,
    R.REGION_KEY
FROM (
    SELECT 'Andhra Pradesh' AS STATE_NAME, 'South' AS REGION_NAME
    UNION ALL
    SELECT 'Bihar', 'North'
    UNION ALL
    SELECT 'Chandigarh', 'North'
    UNION ALL
    SELECT 'Delhi', 'North'
    UNION ALL
    SELECT 'Gujarat', 'West'
    UNION ALL
    SELECT 'Karnataka', 'South'
    UNION ALL
    SELECT 'Kerala', 'South'
    UNION ALL
    SELECT 'Madhya Pradesh', 'North'
    UNION ALL
    SELECT 'Maharashtra', 'West'
    UNION ALL
    SELECT 'Rajasthan', 'North'
    UNION ALL
    SELECT 'Tamil Nadu', 'South'
    UNION ALL
    SELECT 'Telangana', 'South'
    UNION ALL
    SELECT 'Uttar Pradesh', 'North'
    UNION ALL
    SELECT 'West Bengal', 'East'
) X
JOIN DIM_REGION R
    ON X.REGION_NAME = R.REGION_NAME;
SELECT
    S.STATE_KEY,
    S.STATE_NAME,
    R.REGION_NAME
FROM DIM_STATE S
JOIN DIM_REGION R
    ON S.REGION_KEY = R.REGION_KEY
ORDER BY S.STATE_NAME;

CREATE OR REPLACE TABLE DIM_CITY(
CITY_KEY INTEGER AUTOINCREMENT,
CITY_NAME VARCHAR(100) NOT NULL,
STATE_KEY INTEGER NOT NULL,
CONSTRAINT PK_DIM_CITY PRIMARY KEY (CITY_KEY),
CONSTRAINT FK_CITY_STATE FOREIGN KEY (STATE_KEY) REFERENCES DIM_STATE(STATE_KEY)
);
INSERT INTO DIM_CITY(
CITY_NAME,STATE_KEY 
)
SELECT DISTINCT X.CITY_NAME,S.STATE_KEY FROM (
SELECT CITY AS CITY_NAME,STATE FROM STG_CUSTOMERS 
UNION SELECT CITY AS CITY_NAME,STATE FROM STG_BRANCHES 
) X JOIN DIM_STATE S ON X.STATE=S.STATE_NAME;
SELECT C.CITY_KEY,C.CITY_NAME,S.STATE_NAME FROM DIM_CITY C JOIN DIM_STATE S 
ON C.STATE_KEY=S.STATE_KEY ORDER BY S.STATE_NAME,C.CITY_NAME;

CREATE OR REPLACE TABLE DIM_CATEGORY(
CATEGORY_KEY INTEGER AUTOINCREMENT,
CATEGORY_NAME VARCHAR(100) NOT NULL,
CONSTRAINT PK_DIM_CATEGORY PRIMARY KEY (CATEGORY_KEY)
);
INSERT INTO DIM_CATEGORY (
    CATEGORY_NAME
)
SELECT DISTINCT
    CATEGORY
FROM STG_PRODUCTS
ORDER BY CATEGORY;
SELECT * FROM DIM_CATEGORY ORDER BY CATEGORY_KEY;

CREATE OR REPLACE TABLE DIM_BRAND(
BRAND_KEY INTEGER AUTOINCREMENT,
BRAND_NAME VARCHAR(100) NOT NULL,
CATEGORY_KEY INTEGER NOT NULL,
CONSTRAINT PK_DIM_BRAND PRIMARY KEY (BRAND_KEY),
CONSTRAINT FK_BRAND_CATEGORY FOREIGN KEY (CATEGORY_KEY)
REFERENCES DIM_CATEGORY(CATEGORY_KEY)
);
INSERT INTO DIM_BRAND( BRAND_NAME,CATEGORY_KEY)
SELECT DISTINCT P.BRAND,C.CATEGORY_KEY FROM STG_PRODUCTS P 
JOIN DIM_CATEGORY C ON P.CATEGORY=C.CATEGORY_NAME;
SELECT B.BRAND_KEY,B.BRAND_NAME,C.CATEGORY_NAME FROM DIM_BRAND B 
JOIN DIM_CATEGORY C ON B.CATEGORY_KEY=C.CATEGORY_KEY 
ORDER BY C.CATEGORY_NAME,B.BRAND_NAME;

CREATE OR REPLACE TABLE DIM_PRODUCT (
    PRODUCT_KEY INTEGER AUTOINCREMENT,
    PRODUCT_ID INTEGER NOT NULL,
    PRODUCT_NAME VARCHAR(100) NOT NULL,
    BRAND_KEY INTEGER NOT NULL,
    PRICE NUMBER(12,2),

    CONSTRAINT PK_DIM_PRODUCT
        PRIMARY KEY (PRODUCT_KEY),

    CONSTRAINT FK_PRODUCT_BRAND
        FOREIGN KEY (BRAND_KEY)
        REFERENCES DIM_BRAND(BRAND_KEY)
);
INSERT INTO DIM_PRODUCT (
    PRODUCT_ID,
    PRODUCT_NAME,
    BRAND_KEY,
    PRICE
)
SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    B.BRAND_KEY,
    P.PRICE
FROM STG_PRODUCTS P
JOIN DIM_BRAND B
    ON P.BRAND = B.BRAND_NAME
JOIN DIM_CATEGORY C
    ON B.CATEGORY_KEY = C.CATEGORY_KEY
   AND P.CATEGORY = C.CATEGORY_NAME;
SELECT C.CATEGORY_NAME,B.BRAND_NAME,P.PRODUCT_ID,P.PRODUCT_NAME,P.PRICE 
FROM DIM_PRODUCT P JOIN DIM_BRAND B ON P.BRAND_KEY=B.BRAND_KEY 
JOIN DIM_CATEGORY C ON B.CATEGORY_KEY=C.CATEGORY_KEY 
ORDER BY C.CATEGORY_NAME,B.BRAND_NAME,P.PRODUCT_NAME;

CREATE OR REPLACE TABLE DIM_BRANCH(
BRANCH_KEY INTEGER AUTOINCREMENT,
BRANCH_ID INTEGER NOT NULL,
BRANCH_NAME VARCHAR(100) NOT NULL,
CITY_KEY INTEGER NOT NULL,
MANAGER_NAME VARCHAR(100),
CONSTRAINT PK_DIM_BRANCH PRIMARY KEY (BRANCH_KEY),
CONSTRAINT FK_BRANCH_CITY FOREIGN KEY (CITY_KEY) REFERENCES DIM_CITY(CITY_KEY)
);
INSERT INTO DIM_BRANCH( BRANCH_ID,BRANCH_NAME,CITY_KEY,MANAGER_NAME)
SELECT B.BRANCH_ID,B.BRANCH_NAME,C.CITY_KEY,B.MANAGER_NAME FROM STG_BRANCHES B 
JOIN DIM_CITY C ON B.CITY=C.CITY_NAME JOIN DIM_STATE S ON C.STATE_KEY=S.STATE_KEY 
AND B.STATE=S.STATE_NAME;
SELECT R.REGION_NAME,S.STATE_NAME,C.CITY_NAME,B.BRANCH_ID,B.BRANCH_NAME,B.MANAGER_NAME 
FROM DIM_BRANCH B JOIN DIM_CITY C ON B.CITY_KEY=C.CITY_KEY JOIN DIM_STATE S 
ON C.STATE_KEY=S.STATE_KEY JOIN DIM_REGION R ON S.REGION_KEY=R.REGION_KEY 
ORDER BY R.REGION_NAME,S.STATE_NAME,C.CITY_NAME;

CREATE OR REPLACE TABLE DIM_CUSTOMER(
CUSTOMER_KEY INTEGER AUTOINCREMENT,
CUSTOMER_ID INTEGER NOT NULL,
CUSTOMER_NAME VARCHAR(100) NOT NULL,
CITY_KEY INTEGER NOT NULL,
MEMBERSHIP VARCHAR(50),
CONSTRAINT PK_DIM_CUSTOMER PRIMARY KEY (CUSTOMER_KEY),
CONSTRAINT FK_CUSTOMER_CITY FOREIGN KEY (CITY_KEY) REFERENCES DIM_CITY(CITY_KEY)
);
--LOAD CUSTOMERS
INSERT INTO DIM_CUSTOMER (
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY_KEY,
    MEMBERSHIP
)
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    CI.CITY_KEY,
    C.MEMBERSHIP
FROM STG_CUSTOMERS C
JOIN DIM_CITY CI
    ON C.CITY = CI.CITY_NAME
JOIN DIM_STATE S
    ON CI.STATE_KEY = S.STATE_KEY
   AND C.STATE = S.STATE_NAME;
   SELECT
    S.STATE_NAME,
    C.CITY_NAME,
    CU.CUSTOMER_ID,
    CU.CUSTOMER_NAME,
    CU.MEMBERSHIP
FROM DIM_CUSTOMER CU
JOIN DIM_CITY C
    ON CU.CITY_KEY = C.CITY_KEY
JOIN DIM_STATE S
    ON C.STATE_KEY = S.STATE_KEY
ORDER BY
    S.STATE_NAME,
    C.CITY_NAME,
    CU.CUSTOMER_NAME;
SELECT
    S.STATE_NAME,
    COUNT(DISTINCT C.CITY_KEY) AS CITY_COUNT,
    COUNT(DISTINCT CU.CUSTOMER_KEY) AS CUSTOMER_COUNT
FROM DIM_CUSTOMER CU
JOIN DIM_CITY C
    ON CU.CITY_KEY = C.CITY_KEY
JOIN DIM_STATE S
    ON C.STATE_KEY = S.STATE_KEY
GROUP BY S.STATE_NAME
ORDER BY S.STATE_NAME;

CREATE OR REPLACE TABLE DIM_YEAR (
    YEAR_KEY INTEGER AUTOINCREMENT,
    YEAR_NUMBER INTEGER NOT NULL,

    CONSTRAINT PK_DIM_YEAR
        PRIMARY KEY (YEAR_KEY)
);
