    C.MONTH_NAME,
    Q.QUARTER_KEY
FROM STG_CALENDAR C
JOIN DIM_QUARTER Q
    ON C.QUARTER_NAME = Q.QUARTER_NAME
JOIN DIM_YEAR Y
    ON C.YEAR_NUMBER = Y.YEAR_NUMBER
   AND Q.YEAR_KEY = Y.YEAR_KEY;

CREATE OR REPLACE TABLE DIM_DATE (
    DATE_KEY INTEGER AUTOINCREMENT,
    DATE_ID INTEGER NOT NULL,
    DATE_VALUE DATE NOT NULL,
    DAY_NUMBER INTEGER,
    DAY_NAME VARCHAR(20),
    WEEK_NO INTEGER,
    MONTH_KEY INTEGER NOT NULL,
    IS_WEEKEND VARCHAR(10),

    CONSTRAINT PK_DIM_DATE
        PRIMARY KEY (DATE_KEY),

    CONSTRAINT FK_DATE_MONTH
        FOREIGN KEY (MONTH_KEY)
        REFERENCES DIM_MONTH(MONTH_KEY)
);
INSERT INTO DIM_DATE (
    DATE_ID,
    DATE_VALUE,
    DAY_NUMBER,
    DAY_NAME,
    WEEK_NO,
    MONTH_KEY,
    IS_WEEKEND
)
SELECT
    C.DATE_ID,
    C.DATE_VALUE,
    C.DAY_NUMBER,
    C.DAY_NAME,
    C.WEEK_NO,
    M.MONTH_KEY,
    C.IS_WEEKEND
FROM STG_CALENDAR C
JOIN DIM_MONTH M
    ON C.MONTH_NAME = M.MONTH_NAME
JOIN DIM_QUARTER Q
    ON M.QUARTER_KEY = Q.QUARTER_KEY
   AND C.QUARTER_NAME = Q.QUARTER_NAME
JOIN DIM_YEAR Y
    ON Q.YEAR_KEY = Y.YEAR_KEY
   AND C.YEAR_NUMBER = Y.YEAR_NUMBER;

CREATE OR REPLACE TABLE FACT_SALES (
    SALE_KEY INTEGER AUTOINCREMENT,
    SALE_ID INTEGER NOT NULL,
    CUSTOMER_KEY INTEGER NOT NULL,
    PRODUCT_KEY INTEGER NOT NULL,
    BRANCH_KEY INTEGER NOT NULL,
    DATE_KEY INTEGER NOT NULL,
    QUANTITY INTEGER NOT NULL,
    TOTAL_AMOUNT NUMBER(14,2) NOT NULL,

    CONSTRAINT PK_FACT_SALES
        PRIMARY KEY (SALE_KEY),

    CONSTRAINT FK_FACT_CUSTOMER
        FOREIGN KEY (CUSTOMER_KEY)
        REFERENCES DIM_CUSTOMER(CUSTOMER_KEY),

    CONSTRAINT FK_FACT_PRODUCT
        FOREIGN KEY (PRODUCT_KEY)
        REFERENCES DIM_PRODUCT(PRODUCT_KEY),

    CONSTRAINT FK_FACT_BRANCH
        FOREIGN KEY (BRANCH_KEY)
        REFERENCES DIM_BRANCH(BRANCH_KEY),

    CONSTRAINT FK_FACT_DATE
        FOREIGN KEY (DATE_KEY)
        REFERENCES DIM_DATE(DATE_KEY)
);
INSERT INTO FACT_SALES (
    SALE_ID,
    CUSTOMER_KEY,
    PRODUCT_KEY,
    BRANCH_KEY,
    DATE_KEY,
    QUANTITY,
    TOTAL_AMOUNT
)
SELECT
    S.SALE_ID,
    C.CUSTOMER_KEY,
    P.PRODUCT_KEY,
    B.BRANCH_KEY,
    D.DATE_KEY,
    S.QUANTITY,
    S.TOTAL_AMOUNT
FROM STG_SALES S
JOIN DIM_CUSTOMER C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
JOIN DIM_PRODUCT P
    ON S.PRODUCT_ID = P.PRODUCT_ID
JOIN DIM_BRANCH B
    ON S.BRANCH_ID = B.BRANCH_ID
JOIN DIM_DATE D
    ON S.DATE_ID = D.DATE_ID;

SELECT
    COUNT(*) AS TOTAL_FACT_ROWS,
    COUNT(C.CUSTOMER_KEY) AS VALID_CUSTOMERS,
    COUNT(P.PRODUCT_KEY) AS VALID_PRODUCTS,
    COUNT(B.BRANCH_KEY) AS VALID_BRANCHES,
    COUNT(D.DATE_KEY) AS VALID_DATES
FROM FACT_SALES F
LEFT JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_KEY = C.CUSTOMER_KEY
LEFT JOIN DIM_PRODUCT P
    ON F.PRODUCT_KEY = P.PRODUCT_KEY
LEFT JOIN DIM_BRANCH B
    ON F.BRANCH_KEY = B.BRANCH_KEY
LEFT JOIN DIM_DATE D
    ON F.DATE_KEY = D.DATE_KEY;

--CUSTOMER-WISE SALES
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(F.QUANTITY) AS TOTAL_QUANTITY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_SALES
FROM FACT_SALES F
JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_KEY = C.CUSTOMER_KEY
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
ORDER BY TOTAL_SALES DESC;

--PRODUCT-WISE REVENUE
SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    SUM(F.QUANTITY) AS TOTAL_QUANTITY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_KEY = P.PRODUCT_KEY
GROUP BY
    P.PRODUCT_ID,
    P.PRODUCT_NAME
ORDER BY TOTAL_REVENUE DESC;

--BRAND-WISE REVENUE
SELECT
    B.BRAND_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_KEY = P.PRODUCT_KEY
JOIN DIM_BRAND B
    ON P.BRAND_KEY = B.BRAND_KEY
GROUP BY B.BRAND_NAME
ORDER BY TOTAL_REVENUE DESC;

--CATEGORY-WISE REVENUE
SELECT
    C.CATEGORY_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_KEY = P.PRODUCT_KEY
JOIN DIM_BRAND B
    ON P.BRAND_KEY = B.BRAND_KEY
JOIN DIM_CATEGORY C
    ON B.CATEGORY_KEY = C.CATEGORY_KEY
GROUP BY C.CATEGORY_NAME
ORDER BY TOTAL_REVENUE DESC;

--CITY-WISE SALES
SELECT
    C.CITY_NAME,
    SUM(F.QUANTITY) AS TOTAL_QUANTITY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_SALES
FROM FACT_SALES F
JOIN DIM_BRANCH B
    ON F.BRANCH_KEY = B.BRANCH_KEY
JOIN DIM_CITY C
    ON B.CITY_KEY = C.CITY_KEY
GROUP BY C.CITY_NAME
ORDER BY TOTAL_SALES DESC;

--STATE-WISE REVENUE
SELECT
    S.STATE_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH B
    ON F.BRANCH_KEY = B.BRANCH_KEY
JOIN DIM_CITY C
    ON B.CITY_KEY = C.CITY_KEY
JOIN DIM_STATE S
    ON C.STATE_KEY = S.STATE_KEY
GROUP BY S.STATE_NAME
ORDER BY TOTAL_REVENUE DESC;

--REGION-WISE REVENUE
SELECT
    R.REGION_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH B
    ON F.BRANCH_KEY = B.BRANCH_KEY
JOIN DIM_CITY C
    ON B.CITY_KEY = C.CITY_KEY
JOIN DIM_STATE S
    ON C.STATE_KEY = S.STATE_KEY
JOIN DIM_REGION R
    ON S.REGION_KEY = R.REGION_KEY
GROUP BY R.REGION_NAME
ORDER BY TOTAL_REVENUE DESC;

--MONTHLY REVENUE 
SELECT
    M.MONTH_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_DATE D
    ON F.DATE_KEY = D.DATE_KEY
JOIN DIM_MONTH M
    ON D.MONTH_KEY = M.MONTH_KEY
GROUP BY M.MONTH_NAME
ORDER BY TOTAL_REVENUE DESC;

--QUARTERLY REVENUE
SELECT
    Q.QUARTER_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_DATE D
    ON F.DATE_KEY = D.DATE_KEY
JOIN DIM_MONTH M
    ON D.MONTH_KEY = M.MONTH_KEY
JOIN DIM_QUARTER Q
    ON M.QUARTER_KEY = Q.QUARTER_KEY
GROUP BY Q.QUARTER_NAME
ORDER BY TOTAL_REVENUE DESC;

--TOP 10 CUSTOMERS
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_KEY = C.CUSTOMER_KEY
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

--TOP 10 PRODUCTS
SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_KEY = P.PRODUCT_KEY
GROUP BY
    P.PRODUCT_ID,
    P.PRODUCT_NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

--TOP 10 BRANCHES
SELECT
    B.BRANCH_ID,
    B.BRANCH_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH B
    ON F.BRANCH_KEY = B.BRANCH_KEY
GROUP BY
    B.BRANCH_ID,
    B.BRANCH_NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

--CUSTOMER PURCHASE TREND
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    D.DATE_VALUE,
    SUM(F.TOTAL_AMOUNT) AS DAILY_PURCHASE
FROM FACT_SALES F
JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_KEY = C.CUSTOMER_KEY
JOIN DIM_DATE D
    ON F.DATE_KEY = D.DATE_KEY
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    D.DATE_VALUE
ORDER BY
    C.CUSTOMER_ID,
    D.DATE_VALUE;

--PRODUCT PERFORMANCE DASHBOARD
SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    B.BRAND_NAME,
    C.CATEGORY_NAME,
    SUM(F.QUANTITY) AS TOTAL_QUANTITY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    ROUND(
        SUM(F.TOTAL_AMOUNT) / NULLIF(SUM(F.QUANTITY), 0),
        2
    ) AS AVG_SELLING_VALUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_KEY = P.PRODUCT_KEY
JOIN DIM_BRAND B
    ON P.BRAND_KEY = B.BRAND_KEY
JOIN DIM_CATEGORY C
    ON B.CATEGORY_KEY = C.CATEGORY_KEY
GROUP BY
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    B.BRAND_NAME,
    C.CATEGORY_NAME
ORDER BY TOTAL_REVENUE DESC;

--REGIONAL SALES DASHBOARD
SELECT
    R.REGION_NAME,
    S.STATE_NAME,
    C.CITY_NAME,
    SUM(F.QUANTITY) AS TOTAL_QUANTITY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH BR
    ON F.BRANCH_KEY = BR.BRANCH_KEY
JOIN DIM_CITY C
    ON BR.CITY_KEY = C.CITY_KEY
JOIN DIM_STATE S
    ON C.STATE_KEY = S.STATE_KEY
JOIN DIM_REGION R
    ON S.REGION_KEY = R.REGION_KEY
GROUP BY
    R.REGION_NAME,
    S.STATE_NAME,
    C.CITY_NAME
ORDER BY
    R.REGION_NAME,
    TOTAL_REVENUE DESC;

