--CREATE TASK
CREATE OR REPLACE TASK DAILY_SALES_INCREMENTAL_LOAD WAREHOUSE=ENTERPRISE_WH
SCHEDULE='USING CRON 0 0 * * * UTC' AS
MERGE INTO SALES AS TARGET USING NEW_SALES AS SOURCE 
ON TARGET.SALE_ID=SOURCE.SALE_ID 
WHEN MATCHED THEN UPDATE SET
TARGET.CUSTOMER_ID=SOURCE.CUSTOMER_ID,
TARGET.PRODUCT_ID=SOURCE.PRODUCT_ID,
TARGET.BRANCH_ID=SOURCE.BRANCH_ID,
TARGET.QUANTITY=SOURCE.QUANTITY,
TARGET.SALE_DATE=SOURCE.SALE_DATE,
TARGET.TOTAL_AMOUNT=SOURCE.TOTAL_AMOUNT
WHEN NOT MATCHED THEN INSERT(
SALE_ID,CUSTOMER_ID,PRODUCT_ID,BRANCH_ID,QUANTITY,SALE_DATE,TOTAL_AMOUNT
) VALUES (
SOURCE.SALE_ID,SOURCE.CUSTOMER_ID,SOURCE.PRODUCT_ID,SOURCE.BRANCH_ID,
SOURCE.QUANTITY,SOURCE.SALE_DATE,SOURCE.TOTAL_AMOUNT
);

--RESUME TASK
ALTER TASK DAILY_SALES_INCREMENTAL_LOAD RESUME;
SHOW TASKS;
--FOR MANUAL EXCUTION
EXECUTE TASK DAILY_SALES_INCREMENTAL_LOAD;

--VERIFY TASK EXECUTION
SELECT NAME,STATE,SCHEDULED_TIME,COMPLETED_TIME,ERROR_MESSAGE FROM TABLE(
