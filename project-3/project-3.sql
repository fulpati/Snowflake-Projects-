--BUSINEES ANALYTICS: CUSTOMER REVENUE REPORT
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,C.CITY,C.MEMBERSHIP,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM SALES S 
JOIN CUSTOMERS C ON S.CUSTOMER_ID=C.CUSTOMER_ID GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME,C.CITY,C.MEMBERSHIP 
ORDER BY TOTAL_REVENUE DESC;

--BRANCH REVENUE REPORT
SELECT B.BRANCH_ID,B.BRANCH_NAME,B.STATE,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM SALES S 
JOIN BRANCHES B ON S.BRANCH_ID=B.BRANCH_ID GROUP BY B.BRANCH_ID,B.BRANCH_NAME,B.STATE 
ORDER BY TOTAL_REVENUE DESC;

--PRODUCT REVENUE REPORT
SELECT P.PRODUCT_ID,P.PRODUCT_NAME,P.CATEGORY,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM SALES S
JOIN PRODUCTS P ON S.PRODUCT_ID=P.PRODUCT_ID GROUP BY P.PRODUCT_ID,P.PRODUCT_NAME,P.CATEGORY ORDER BY TOTAL_REVENUE DESC;

--MONTHLY REVENUE REPORT
SELECT DATE_TRUNC('MONTH',SALE_DATE) AS SALES_MONTH,SUM(TOTAL_AMOUNT) AS MONTHLY_REVENUE FROM SALES 
GROUP BY DATE_TRUNC('MONTH',SALE_DATE) ORDER BY SALES_MONTH;

--HIGHEST REVENUE CUSTOMER
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM SALES S 
JOIN CUSTOMERS C ON S.CUSTOMER_ID=C.CUSTOMER_ID GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME 
ORDER BY TOTAL_REVENUE DESC LIMIT 1;

--HIGEST REVENUE BRANCH
SELECT B.BRANCH_ID,B.BRANCH_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM SALES S 
JOIN BRANCHES B ON S.BRANCH_ID=B.BRANCH_ID GROUP BY B.BRANCH_ID,B.BRANCH_NAME 
ORDER BY TOTAL_REVENUE DESC LIMIT 1;

--TOP 5 PRODUCTS 
SELECT P.PRODUCT_ID,P.PRODUCT_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM SALES S 
JOIN PRODUCTS P ON S.PRODUCT_ID=P.PRODUCT_ID GROUP BY P.PRODUCT_ID,P.PRODUCT_NAME
ORDER BY TOTAL_REVENUE DESC LIMIT 5;

--CUSTOMER PURCHASE FREQUENCY
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,COUNT(S.SALE_ID) AS PURCHASE_FREQUENCY FROM SALES S 
JOIN CUSTOMERS C ON S.CUSTOMER_ID=C.CUSTOMER_ID GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME 
ORDER BY PURCHASE_FREQUENCY DESC;

--RUNNING REVENUE
SELECT SALE_ID,SALE_DATE,TOTAL_AMOUNT,SUM(TOTAL_AMOUNT) OVER (
ORDER BY SALE_DATE,SALE_ID
ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW 
) AS RUNNING_REVENUE FROM SALES ORDER BY SALE_DATE,SALE_ID;

--CUSTOMER RANKING
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE,RANK() OVER (
ORDER BY SUM(S.TOTAL_AMOUNT) DESC 
) AS CUSTOMER_RANK FROM SALES S JOIN CUSTOMERS C ON S.CUSTOMER_ID=C.CUSTOMER_ID 
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME ORDER BY CUSTOMER_RANK;

--CUSTOMER_REVENUE VIEW
CREATE OR REPLACE VIEW CUSTOMER_REVENUE AS 
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,C.CITY,C.MEMBERSHIP,SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE FROM SALES S 
JOIN CUSTOMERS C ON S.CUSTOMER_ID=C.CUSTOMER_ID 
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME,C.CITY,C.MEMBERSHIP;
SELECT * FROM CUSTOMER_REVENUE ORDER BY TOTAL_REVENUE DESC; 

--MATERIALIZED VIEW BRANCH_REVENUE
CREATE OR REPLACE MATERIALIZED VIEW BRANCH_REVENUE AS 
SELECT BRANCH_ID,SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE FROM SALES
GROUP BY BRANCH_ID;
SELECT * FROM BRANCH_REVENUE ORDER BY TOTAL_REVENUE DESC;