CREATE TABLE SALES(
SALE_ID INTEGER,
CUSTOMER_ID INTEGER,
PRODUCT_ID INTEGER,
BRANCH_ID INTEGER,
QUANTITY INTEGER,
SALE_DATE DATE,
TOTAL_AMOUNT NUMBER(12,2)
);

